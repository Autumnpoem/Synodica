/**
 * Where an employee's brain runs.
 * - claude: Claude Code via the Agent SDK. Your Claude subscription login by default, or an API key.
 * - codex:  OpenAI Codex CLI (`codex exec`). Your ChatGPT/Codex subscription login.
 * - gemini: Google Gemini CLI. Your Google account (the same one Antigravity uses).
 * - openai: any OpenAI-compatible chat API: Kimi/Moonshot, OpenRouter, DeepSeek, Groq, xAI, Ollama…
 */
export type ProviderKind = 'claude' | 'codex' | 'gemini' | 'openai'

export interface ProviderDef {
  kind: ProviderKind
  label: string
  /** API key. For `claude` it switches from subscription login to API billing. */
  apiKey?: string
  /** Claude gateways: select x-api-key (default) or Authorization: Bearer. Stored secret stays in apiKey. */
  authMode?: 'api-key' | 'auth-token'
  /** Base URL for `openai` providers (e.g. https://api.moonshot.ai/v1). */
  baseUrl?: string
  /** Model ids offered in the picker. Free text is always allowed. */
  models?: string[]
  /**
   * `openai` providers only: send the model's streamed reasoning (`reasoning_content`) back with
   * its tool calls inside one reply's tool loop. Some thinking models need it to continue;
   * set false if a provider rejects it. Defaults to true.
   */
  echoReasoning?: boolean
}

/** A model picker snapshot. CLI/upstream rows describe the queried catalog, not account entitlement. */
export interface ProviderModelCatalog {
  provider: string
  models: { id: string; label: string; description?: string; inputModalities?: string[] }[]
  source: 'upstream' | 'cli' | 'configured' | 'unavailable'
  /** `default` delegates model choice to the CLI; it is not a stable model ID. */
  supportsDefault: boolean
  updatedAt: number
  error?: 'missing-credential' | 'unavailable' | 'unsupported'
}

