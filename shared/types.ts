export interface Message {
  id: string
  /** Correlates the owner message with its accepted HTTP send after a lost response. */
  requestId?: string
  conversationId: string
  authorId: string
  text: string
  createdAt: number
  status: MessageStatus
  /** Short tool-activity lines shown under a streaming bubble (e.g. "Read server/index.ts"). */
  activity?: string[]
  usage?: MessageUsage
  attachments?: Attachment[]
  replyTo?: { messageId: string; authorId: string; excerpt: string }
  /** Set on messages produced by a project workflow step (task id, or PLAN / CRITIQUE / FINAL). */
  taskRef?: string
  /** Set on the owner's interrupt-and-correct messages (the correction record id). */
  correctionId?: string
  /**
   * Set on server notes (workflow and correction lines): the localizable form of `text`. `text` keeps
   * the English rendering for history, exports and employees' context; the UI renders this in its locale.
   */
  note?: NotePart[]
}

/** Value of a note placeholder: literal text (names, ids, user words, paths) or a nested note key. */
export type NoteVar = string | number | { key: string }

/** One localizable piece of a server note. `br` newlines go before it when parts are joined. */
export interface NotePart {
  key: string
  vars?: Record<string, NoteVar>
  br?: number
}

/**
 * stopping: the old run was asked to stop and has not relinquished its turn and locks yet ·
 * stopped: nothing old is running any more · applied: the corrected run continues (or waits for your
 * resume / re-plan choice) · superseded: a newer correction arrived first and carries this one ·
 * pending-restart: the server restarted before it was applied; nothing old is replayed automatically.
 */
export type CorrectionStatus = 'stopping' | 'stopped' | 'applied' | 'superseded' | 'pending-restart'

/** continue: small correction, the same work goes on with it · replan: it changes scope, you choose Resume or Kickoff. */
export type CorrectionMode = 'continue' | 'replan'

export interface CorrectionRecord {
  id: string
  conversationId: string
  projectId?: string
  /** The owner's original words. */
  text: string
  mode: CorrectionMode
  status: CorrectionStatus
  /** Project instruction revision this correction created (0 in ordinary chats). */
  revision: number
  /** The step or task that was running when the correction arrived, if any. */
  interrupted?: string
  /** Whether a provider turn was still running when the correction arrived. */
  wasRunning: boolean
  /** Truthful progress, e.g. which turn has not confirmed cancellation yet. */
  detail?: string
  /** Localizable form of `detail` (the UI renders it in its locale; `detail` stays English). */
  detailNote?: NotePart[]
  messageId?: string
  createdAt: number
  updatedAt: number
}

export type ConversationKind = 'group' | 'dm'

