/**
 * What one employee is doing right now. Driven only by real events (turn start, tool calls,
 * approvals, task state); V2's office view and desktop pet render this, nothing else.
 */
export type AgentActivityState =
  | 'idle' // nothing assigned
  | 'queued' // has ready work waiting for a slot
  | 'thinking' // a provider turn is running, no tool yet
  | 'tool' // executing a tool
  | 'waiting-approval'
  | 'waiting-dependency'
  | 'waiting-user'
  | 'error'
  | 'interrupted'
  | 'offline' // provider known to be unavailable
  | 'replied' // a few seconds after a turn that posted a reply (not a delivered or accepted task)
  | 'done' // a few seconds after a task this employee owns was accepted

/** What the latest tool line was doing, classified from its tool name. */
export type ToolKind = 'file' | 'command' | 'read' | 'web' | 'other'

export interface AgentActivity {
  agentId: string
  state: AgentActivityState
  since: number
  conversationId?: string
  projectId?: string
  taskRef?: string
  /**
   * Safe, bounded status text: a tool name (or a web host), a task id, or a classified reason.
   * Never tool input, command arguments, URL paths or queries, or raw error payloads.
   */
  detail?: string
  lastActiveAt?: number
  /** state "tool": what kind of tool the latest line was. */
  toolKind?: ToolKind
  /** Live turns: when the provider last produced anything (text, a tool line, an approval request). */
  lastEventAt?: number
}

/** Coarse buckets for today's time accounting. Waiting is never counted as idle. */
export type LedgerBucket = 'working' | 'waiting' | 'idle' | 'problem'

/**
 * One employee's observed time today (server local day), from timestamped state transitions.
 * Only time the server actually observed counts; a restart leaves a gap, not invented time.
 */
export interface AgentLedgerDay {
  agentId: string
  /** Local date, YYYY-MM-DD. */
  day: string
  /** Closed milliseconds per bucket. The open segment (since `openSince`) is not included. */
  totals: Record<LedgerBucket, number>
  /** First moment observed today. */
  observedFrom: number
  /** Bucket and start of the segment still running, if any. */
  open?: { bucket: LedgerBucket; since: number; state: AgentActivityState }
  /** The latest transitions today, oldest first, at most LEDGER_TIMELINE entries. "unknown" marks a gap (server stopped). */
  timeline: { at: number; state: AgentActivityState | 'unknown' }[]
}

