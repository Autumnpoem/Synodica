/** Native names for the language switch (shown the same in every locale). */
export const LOCALE_NAMES: Record<Locale, string> = { en: 'English', 'zh-CN': decodeResource('\\u7b80\\u4f53\\u4e2d\\u6587') }

export const RESOURCES: Record<Locale, Partial<Messages>> = { en: EN, 'zh-CN': ZH_CN }

/** Keys a locale lacks (tests; a missing key falls back to English at runtime). */
export function missingKeys(locale: Locale): MessageKey[] {
  const res = RESOURCES[locale]
  return (Object.keys(EN) as MessageKey[]).filter((k) => typeof res[k] !== 'string' || (res[k] as string).trim() === '')
}

/** Keys in a locale that English does not define (stale or misspelled resource entries). */
export function extraKeys(locale: Locale): string[] {
  return Object.keys(RESOURCES[locale]).filter((k) => !(k in EN))
}

/** Placeholders ({name}) in a string, sorted, for consistency checks. */
export function placeholders(s: string): string[] {
  return [...s.matchAll(/\{([a-zA-Z]+)\}/g)].map((m) => m[1] as string).sort()
}

/**
 * Look up and interpolate. Falls back to English for a missing key, and leaves an unknown
 * placeholder visible. Values are inserted as plain text (React escapes them).
 */
export function translate(locale: Locale, key: MessageKey, vars: Record<string, string | number> = {}): string {
  const template = RESOURCES[locale]?.[key] ?? EN[key] ?? key
  return template.replace(/\{([a-zA-Z]+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole))
}

export function isLocale(v: unknown): v is Locale {
  return v === 'en' || v === 'zh-CN'
}

/** The initial UI locale: a saved choice wins; otherwise Chinese on a Chinese OS / browser, English elsewhere. */
export function detectLocale(saved: unknown, languages: readonly string[]): Locale {
  if (isLocale(saved)) return saved
  for (const l of languages) {
    const tag = l.toLowerCase()
    if (tag === 'zh' || tag.startsWith('zh-')) return 'zh-CN'
    if (tag.startsWith('en')) return 'en'
  }
  return 'en'
}

/** The UI locale preference lives in browser storage only: provider, model and team settings are untouched. */
export const LOCALE_STORAGE_KEY = 'ogb.locale'

export interface KeyValueStorage {
  getItem(key: string): string | null
  setItem(key: string, value: string): void
}

export function loadLocale(storage: KeyValueStorage | undefined, languages: readonly string[]): Locale {
  let saved: string | null = null
  try {
    saved = storage?.getItem(LOCALE_STORAGE_KEY) ?? null
  } catch {
    saved = null
  }
  return detectLocale(saved, languages)
}

export function saveLocale(storage: KeyValueStorage | undefined, locale: Locale): void {
  try {
    storage?.setItem(LOCALE_STORAGE_KEY, locale)
  } catch {
    // Private mode / disabled storage: the choice lasts for this page only.
  }
}

/** Reply-language value for "employees reply in Chinese". Off restores auto (mirror the owner). */
export const CHINESE_REPLY_LANGUAGE = 'zh-CN'

/**
 * Reply language for a locale choice. Only a fresh office (no owner message yet) that still has the
 * untouched default "auto" starts replying in Chinese with the Chinese UI; an existing user's
 * setting, including "auto", is never overridden. The explicit switch is in Settings.
 */
export function replyLanguageFor(current: string, locale: Locale, freshOffice: boolean): string {
  if (locale === 'zh-CN' && freshOffice && current === 'auto') return CHINESE_REPLY_LANGUAGE
  return current
}

/** A fresh office: the owner has not written anything in any conversation yet. */
export function isFreshOffice(conversations: readonly { messages: readonly { authorId: string }[] }[]): boolean {
  return conversations.every((c) => c.messages.every((m) => m.authorId !== 'user'))
}

/** Set once this browser made the initial reply-language decision, so turning it off later sticks. */
export const REPLY_DEFAULT_STORAGE_KEY = 'ogb.replyLanguageDecided'

/**
 * The one-time initial reply-language decision for the page: the new value to save, or undefined
 * for "change nothing" (already decided here, an existing office, or a language already chosen).
 */
export function initialReplyLanguage(current: string, locale: Locale, conversations: readonly { messages: readonly { authorId: string }[] }[], decided: boolean): string | undefined {
  if (decided) return undefined
  const next = replyLanguageFor(current, locale, isFreshOffice(conversations))
  return next !== current ? next : undefined
}
